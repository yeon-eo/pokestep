export const PMD_BASE_URL = 'https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master';
export const SHOWDOWN_GIF_BASE = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/showdown';
export const STATIC_SPRITE_BASE = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon';
export const OFFICIAL_ARTWORK_BASE = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork';

// Helper to generate full-body animated moving GIF (Gen 5 Showdown dynamic pixel art)
export function getAnimatedFullBodySpriteUrl(pokedexNo: number): string {
  return `${SHOWDOWN_GIF_BASE}/${pokedexNo}.gif`;
}

// Helper to generate full-body static pixel sprite
export function getStaticFullBodySpriteUrl(pokedexNo: number): string {
  return `${STATIC_SPRITE_BASE}/${pokedexNo}.png`;
}

// Helper to generate official PMD SpriteCollab (CC BY-NC 4.0) pixel-art portrait URLs
export function getPmdPortraitUrl(pokedexNo: number, emotion: string = 'Normal'): string {
  const dex4 = String(pokedexNo).padStart(4, '0');
  return `${PMD_BASE_URL}/portrait/${dex4}/${emotion}.png`;
}

// Helper to generate official PMD SpriteCollab overworld walking sprite sheet
export function getPmdWalkSpriteUrl(pokedexNo: number): string {
  const dex4 = String(pokedexNo).padStart(4, '0');
  return `${PMD_BASE_URL}/sprite/${dex4}/Walk-Anim.png`;
}

